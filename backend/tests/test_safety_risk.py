# C.1 — Adversarial Scenario: Single-source adjacent cell manipulation
# ==========================================================================

class TestC1_AdversarialSingleSourceManipulation:
    """Test adversarial pattern: 1 single device_id reports 5 adjacent grid cells
    over 5 consecutive days in the same neighborhood (e.g. T. Nagar).
    Assess if the heatmap creates a high-intensity hot spot despite coming
    from a single individual."""

    @pytest.mark.asyncio
    async def test_single_device_adjacent_cluster_heatmap_weight(self, client):
        adversary_device = _device_id()
        base_lat = 13.0418
        base_lng = 80.2341

        # Submit 1 report per day across 5 adjacent grid cells (~100m steps)
        for i in range(5):
            body = {
                "lat": base_lat + (i * 0.001),
                "lng": base_lng + (i * 0.001),
                "status": "unsafe",
                "category": "poor_lighting",
                "device_id": adversary_device,
                "note": f"Adversarial report day {i+1}",
            }
            res = await client.post("/reports", json=body)
            assert res.status_code == 201

        # Fetch heatmap
        heatmap_res = await client.get("/reports/heatmap")
        assert heatmap_res.status_code == 200
        points = heatmap_res.json()

        # Total points in cluster
        cluster_points = [
            p for p in points
            if abs(p["lat"] - base_lat) < 0.01 and abs(p["lng"] - base_lng) < 0.01
        ]
        total_cluster_weight = sum(p["weight"] for p in cluster_points)

        # Check total weight generated by 1 single device
        assert len(cluster_points) == 5
        # Return total weight for risk assessment
        print(f"Total cluster weight generated by 1 device across 5 cells: {total_cluster_weight:.2f}")


