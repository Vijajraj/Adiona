# C.3 — Profanity-Filter Flag-For-Review Queue Verification
# ==========================================================================

class TestC3_ProfanityFlagQueueSurfacing:
    """Confirm profanity-flagged reports surface in GET /moderation/reports."""

    @pytest.mark.asyncio
    async def test_flagged_report_surfaces_in_moderation_queue(self, client):
        async with test_session() as db:
            flagged_report = Report(
                grid_lat=13.0827,
                grid_lng=80.2707,
                status=ReportStatus.unsafe,
                category=ReportCategory.poor_lighting,
                note="bad offensive word",
                device_id=_device_id(),
                is_flagged=True,
            )
            db.add(flagged_report)
            await db.commit()
            report_id = flagged_report.id

        # Query moderation reports endpoint with admin key
        admin_key = settings.ADMIN_SECRET
        headers = {"X-Admin-Key": admin_key}

        mod_res = await client.get("/moderation/reports", headers=headers)
        assert mod_res.status_code == 200
        data = mod_res.json()

        # Confirm report appears in flagged queue
        flagged_ids = [item["id"] for item in data]
        assert report_id in flagged_ids, "Profanity-flagged report failed to surface in moderation queue!"
