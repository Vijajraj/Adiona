# C.2 — Time-Decay Logic Verification
# ==========================================================================

class TestC2_TimeDecayWeights:
    """Verify weight difference between a 12-month-old report vs 1-day-old report."""

    @pytest.mark.asyncio
    async def test_time_decay_difference(self, client):
        async with test_session() as db:
            now = datetime.now(timezone.utc)

            # Report 1: 365 days ago (12 months)
            old_report = Report(
                grid_lat=13.0500,
                grid_lng=80.2500,
                status=ReportStatus.unsafe,
                category=ReportCategory.poor_lighting,
                device_id=_device_id(),
                confirmations=0,
                created_at=now - timedelta(days=365),
            )

            # Report 2: 1 day ago
            recent_report = Report(
                grid_lat=13.0600,
                grid_lng=80.2600,
                status=ReportStatus.unsafe,
                category=ReportCategory.poor_lighting,
                device_id=_device_id(),
                confirmations=0,
                created_at=now - timedelta(days=1),
            )

            db.add(old_report)
            db.add(recent_report)
            await db.commit()

        # Fetch heatmap
        heatmap_res = await client.get("/reports/heatmap")
        assert heatmap_res.status_code == 200
        points = heatmap_res.json()

        old_point = next(p for p in points if abs(p["lat"] - 13.0500) < 0.001)
        recent_point = next(p for p in points if abs(p["lat"] - 13.0600) < 0.001)

        print(f"12-month-old report weight: {old_point['weight']}")
        print(f"1-day-old report weight: {recent_point['weight']}")

        # 1-day-old report should have significantly higher weight than 12-month-old report
        assert recent_point["weight"] > old_point["weight"]
        # Old unconfirmed report should hit min decay floor (0.10)
        assert old_point["weight"] == 0.10
        # Recent report should be close to 0.98+
        assert recent_point["weight"] >= 0.95


